export type CategoriaTienda = "macetas" | "fertilizantes" | "herramientas" | "decoracion";

export type TipoObjeto = "maceta" | "luz" | "consumible" | "herramienta" | "decoracion";

export interface ObjetoTienda {
  id: string;
  categoria: CategoriaTienda;
  tipo: TipoObjeto;
  nombre: string;
  efecto: string;
  /** Tiene que coincidir con `tpp.catalogo()` en la base de datos, que es quien decide. */
  precio: number;
  nivel: number;
  /** Columna y fila del icono en la hoja de objetos. */
  celda: [number, number];
  /** Solo se consigue en el pase de temporada: no se vende en la tienda ni en el mercado. */
  exclusivo?: boolean;
  /** Hoja de iconos: la normal (por defecto) o la de los objetos nuevos. */
  hoja?: "nuevos";
  /** Rareza fijada por el diseño; si falta, se deduce del precio. */
  rareza?: Rareza;
  /** Cómo se usa un consumible: sobre la planta activa, para toda la casa o contra una plaga. */
  uso?: "planta" | "casa" | "plaga";
}

